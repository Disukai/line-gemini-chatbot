def build_plan_prompt(topic: str, has_context: bool = False) -> str:
    """Specialized system prompt for /plan command."""
    context_note = (
        "\n📌 ข้อมูลเสริม: มีประวัติการสนทนาก่อนหน้านี้ในกลุ่ม ให้เชื่อมโยงและปรับแผนให้เข้ากับบริบทที่เพื่อนๆ เพิ่งคุยกันด้วย!"
        if has_context else ""
    )
    return f"""
คุณได้รับคำสั่งพิเศษ [/plan] ในกลุ่มเพื่อน
ภารกิจ: วางแผนกลยุทธ์และ Action Plan สำหรับหัวข้อ: "{topic}" อย่างละเอียดที่สุด สมบูรณ์แบบ คมชัด ปฏิบัติได้จริงทันที!{context_note}

โครงสร้างแผนที่ต้องตอบ (ใช้ภาษาพูดของเพื่อนที่เป็นมือโปร วางแผนเก่งมาก):
🎯 **1. เป้าหมาย & นิยามความสำเร็จ (Target Outcome)**
- สรุปเป้าหมายให้ชัดเจน วัดผลได้

📋 **2. แผนปฏิบัติการแบบ Step-by-Step (Action Steps & Milestones)**
- แบ่งเป็น Phase/ขั้นตอน 1, 2, 3...
- แต่ละขั้นบอกชัดเจนว่า: ใครทำอะไร, ใช้เครื่องมืออะไร, ผลลัพธ์คืออะไร

⚠️ **3. จุดตาย & สิ่งที่ต้องระวัง (Pitfalls & Mitigation)**
- อุปสรรคที่มักจะเจอ และวิธีแก้ทางดักไว้ล่วงหน้า

🚀 **4. Next 15 Minutes Quick-Win**
- สิ่งแรกที่สามารถลงมือทำได้ทันทีใน 15 นาทีนี้เพื่อเริ่มขยับโมเมนตัม!

สไตล์: ภาษาเป็นกันเอง ชัดเจน เด็ดขาด มีพลัง ให้เพื่อนอ่านแล้วพร้อมลุยทันที!
""".strip()


def build_boost_prompt(situation: str, has_context: bool = False) -> str:
    """Specialized prompt for /boost command."""
    context_note = (
        "\n📌 ข้อมูลเสริม: มีบทสนทนาของเพื่อนๆ ในกลุ่มอยู่ด้วย ช่วยอ้างอิงสถานการณ์จริงที่เพื่อนกำลังเผชิญมาบูสต์ให้โดนใจ!"
        if has_context else ""
    )
    return f"""
คุณได้รับคำสั่งพิเศษ [/boost] ในกลุ่มเพื่อน
ภารกิจ: ปลุกพลังใจ บูสต์ไฟ กระตุ้นเอเนอร์จี้สำหรับสถานการณ์: "{situation}"{context_note}

แนวทางการบูสต์:
🔥 **1. ปรับ Mindset / Reframe สถานการณ์**: พลิกมุมมองความเครียด/ความยากให้เป็นความท้าทายที่น่าลุย
⚡ **2. Tactical Breakthrough**: ให้ทริคหรือไอเดียเจ๋งๆ 2-3 ข้อที่ช่วยทะลวงจุดตัน ปลดล็อกปัญหานี้ทันที
💪 **3. ปลุกพลังสไตล์เพื่อนแท้**: ให้กำลังใจแบบหนักแน่น ไม่โลกสวย พูดให้ฮึกเหิม เลือดสูบฉีด พร้อมลุยจนสำเร็จ!

สไตล์: มีพลัง ดุดันแบบเป็นกันเอง มั่นใจ กวนๆ เล็กน้อยให้คลายเครียด!
""".strip()


def build_goal_prompt(goal_text: str, has_context: bool = False) -> str:
    """Specialized prompt for /goal command."""
    context_note = (
        "\n📌 ข้อมูลเสริม: อิงบริบทที่เพื่อนๆ กำลังคุยกันในกลุ่ม เพื่อให้เป้าหมายนี้สมจริงและมีพลังที่สุด"
        if has_context else ""
    )
    return f"""
คุณได้รับคำสั่งพิเศษ [/goal] ในกลุ่มเพื่อน
ภารกิจ: แปลงเป้าหมาย "{goal_text}" ให้กลายเป็น SMART Actionable Goal ที่ทำได้จริงและวัดผลได้ชัดเจน{context_note}

โครงสร้างการตอบ:
🎯 **เป้าหมายที่คมชัด (Refined SMART Goal)**: ทำให้เป้าหมายชัดเจน มีตัวเลขหรือผลลัพธ์ที่วัดได้
⏱️ **กรอบเวลา & หมุดหมาย (Milestones)**:
  - สัปดาห์นี้ / เดือนนี้
  - สิ่งที่ต้องสำเร็จในแต่ละช่วง
✅ **Daily Habit / Micro-action**: พฤติกรรมเล็กๆ รายวันที่ต้องทำสม่ำเสมอ
🏁 **Checklist 3 สิ่งแรกที่ต้องทำวันนี้**: เช็คลิสต์ 3 ข้อที่ต้องติ๊กถูกภายในวันนี้!

สไตล์: ชัดเจน โฟกัส เป็นเพื่อนที่คอยดึงให้เพื่อนทำตามเป้าจนสำเร็จ
""".strip()
